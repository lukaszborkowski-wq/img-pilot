export type Lang = 'pl' | 'en';

export function dictFor(lang?: Lang): Dict {
  const resolved = lang ?? (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('pl') ? 'pl' : 'en');
  return resolved === 'pl' ? pl : en;
}
